// Writes packages/core/src/builtin-tools.gen.ts: the built-in tools as the Tools view shows
// them. The agent's own tools come from packages/agent (build it first); the browser tools
// from Playwright MCP itself, listed over stdio (no browser is started for that).
//   pnpm --filter @dodo/agent build && pnpm --filter @dodo/cli catalog
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const agent = await import(path.join(here, '../../../packages/agent/dist/index.js'));
const cli = path.join(
  path.dirname(fileURLToPath(import.meta.resolve('@playwright/mcp/package.json'))),
  'cli.js',
);
const client = new Client({ name: 'dodo-catalog', version: '0.1.0' });
await client.connect(
  new StdioClientTransport({ command: process.execPath, args: [cli, '--headless'] }),
);
const { tools } = await client.listTools();
await client.close();

const all = [...agent.builtinCatalog(), ...agent.browserCatalog(tools)];
const out = path.join(here, '../../../packages/core/src/builtin-tools.gen.ts');
await writeFile(
  out,
  `// Generated by \`pnpm --filter @dodo/cli catalog\`. Do not edit.\nexport const catalog: unknown[] = ${JSON.stringify(all, null, 2)};\n`,
);
console.log(`${all.length} built-in tools written to ${path.relative(process.cwd(), out)}`);
